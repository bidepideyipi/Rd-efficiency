package com.mig.mapsql.core.sql;

import com.mig.mapsql.config.GeneratorProperties;
import com.mig.mapsql.core.model.FieldMapping;
import com.mig.mapsql.core.model.LeftJoinSpec;
import com.mig.mapsql.core.model.MappingType;
import com.mig.mapsql.core.model.TableMapping;
import com.mig.mapsql.core.util.JoinConditionParser;
import com.mig.mapsql.core.util.SqlRuleHeuristics;
import com.mig.mapsql.core.util.Strings;
import org.springframework.stereotype.Component;

import java.util.ArrayList;
import java.util.List;

@Component
public class SelectSqlRenderer {

    private final GeneratorProperties properties;

    public SelectSqlRenderer(GeneratorProperties properties) {
        this.properties = properties;
    }

    public String render(TableMapping table) {
        String primaryAlias = properties.getSourceAlias();
        String target = !Strings.isBlank(table.getTargetTable()) ? table.getTargetTable() : table.getSheetName();
        String source = table.getSourceTable();
        if (Strings.isBlank(source)) {
            throw new IllegalStateException("源表表名为空: " + target);
        }

        List<String> selectParts = new ArrayList<String>();
        for (FieldMapping f : table.getFields()) {
            if (f.getMappingType() == MappingType.SKIP) {
                continue;
            }
            String line = renderField(f, table, primaryAlias);
            if (line == null) {
                continue;
            }
            if (properties.isIncludeHeaderComment() && !Strings.isBlank(f.getTargetComment())) {
                selectParts.add("  -- " + f.getSeq() + " " + f.getTargetComment()
                        + " [" + Strings.trimToEmpty(f.getMappingTypeRaw()) + "]");
            }
            selectParts.add("  " + line);
        }
        if (selectParts.isEmpty()) {
            throw new IllegalStateException("无有效 SELECT 列: " + target);
        }

        List<String> formatted = new ArrayList<String>();
        List<Integer> exprIndexes = new ArrayList<Integer>();
        for (int i = 0; i < selectParts.size(); i++) {
            if (!selectParts.get(i).trim().startsWith("--")) {
                exprIndexes.add(i);
            }
        }
        for (int i = 0; i < selectParts.size(); i++) {
            String part = selectParts.get(i);
            if (part.trim().startsWith("--")) {
                formatted.add(part);
            } else {
                boolean last = exprIndexes.get(exprIndexes.size() - 1) == i;
                formatted.add(last ? part : part + ",");
            }
        }

        StringBuilder sb = new StringBuilder();
        sb.append("-- Generated by map-sql-generator\n");
        sb.append("-- targetTable: ").append(target).append("\n");
        sb.append("-- sourceTable: ").append(source).append("\n");
        if (!table.getLeftJoins().isEmpty()) {
            sb.append("-- joins: ").append(table.getLeftJoins().size()).append("\n");
        }
        sb.append("-- DO NOT EDIT manually unless necessary\n\n");
        sb.append("SELECT\n");
        for (String line : formatted) {
            sb.append(line).append("\n");
        }
        sb.append("FROM ").append(source).append(" ").append(primaryAlias).append("\n");
        for (LeftJoinSpec lj : table.getLeftJoins()) {
            sb.append(lj.sqlKeyword()).append(" ").append(lj.getTableName()).append(" ").append(lj.getAlias())
                    .append(" ON ").append(lj.getOnPredicate()).append("\n");
        }
        sb.append(renderWhere(table, primaryAlias));
        sb.append(";\n");
        return sb.toString();
    }

    private String renderWhere(TableMapping table, String alias) {
        // 无业务 WHERE（如仅写 select * from T）时不拼时间分片，也不生成 AND (select * from …)
        if (Strings.isBlank(table.getJoinPredicate())) {
            return "";
        }
        StringBuilder where = new StringBuilder("WHERE ");
        if ("to_date".equalsIgnoreCase(properties.getTimePredicate())) {
            where.append(alias).append(".{{tmColumn}} >= TO_DATE('{{beginTm}}', '{{tmFormat}}')\n");
            where.append("  AND ").append(alias).append(".{{tmColumn}} <  TO_DATE('{{endTm}}', '{{tmFormat}}')");
        } else {
            where.append(alias).append(".{{tmColumn}} >= '{{beginTm}}'\n");
            where.append("  AND ").append(alias).append(".{{tmColumn}} <  '{{endTm}}'");
        }
        where.append("\n  AND (\n    ").append(table.getJoinPredicate()).append("\n  )");
        where.append("\n");
        return where.toString();
    }

    String renderField(FieldMapping f, TableMapping table, String primaryAlias) {
        String targetCol = f.getTargetColumn();
        if (Strings.isBlank(targetCol)) {
            return null;
        }

        if (!Strings.isBlank(f.getRuleExpression()) && SqlRuleHeuristics.looksLikeSql(f.getRuleExpression())) {
            String expr = SqlRuleHeuristics.normalizeRule(f.getRuleExpression());
            expr = JoinConditionParser.rewritePrimaryAlias(expr, primaryAlias);
            return "(" + expr + ") AS " + targetCol;
        }

        if (f.getMappingType() == MappingType.DEFAULT_VALUE) {
            return "(" + literal(f.getDefaultValue(), f.getTargetType()) + ") AS " + targetCol;
        }

        if (Strings.isBlank(f.getSourceColumn())) {
            throw new IllegalStateException("缺少源列: " + targetCol);
        }

        String alias = JoinConditionParser.resolveJoinAlias(
                f.getJoinCondition(), f.getSourceTable(), table.getLeftJoins(), primaryAlias);
        if (Strings.isBlank(alias)) {
            alias = table.resolveAlias(f.getSourceTable(), primaryAlias);
        }
        String base = alias + "." + f.getSourceColumn().trim();
        boolean needCast = TypeCastSupport.typeDiffers(f.getSourceType(), f.getTargetType());
        if (needCast) {
            base = TypeCastSupport.applyTypeCast(base, f.getSourceType(), f.getTargetType(), properties.getDateFormat());
        }

        Integer srcLen = TypeCastSupport.charLength(f.getSourceLength());
        Integer tgtLen = TypeCastSupport.charLength(f.getTargetLength());
        if (!needCast && srcLen != null && tgtLen != null && srcLen > tgtLen
                && TypeCastSupport.isCharType(f.getSourceType())
                && TypeCastSupport.isCharType(f.getTargetType())
                && !"error".equalsIgnoreCase(properties.getLengthOverflow())) {
            base = "CASE WHEN LENGTH(" + base + ") > " + tgtLen
                    + " THEN SUBSTR(" + base + ", 1, " + tgtLen + ")"
                    + " ELSE " + base + " END";
        }

        return "(" + base + ") AS " + targetCol;
    }

    static String literal(String value, String targetType) {
        if (value == null) {
            return "NULL";
        }
        String v = value.trim();
        if (v.equalsIgnoreCase("NULL")) {
            return "NULL";
        }
        if (TypeCastSupport.isNumberType(targetType)) {
            return v;
        }
        return "'" + v.replace("'", "''") + "'";
    }
}
